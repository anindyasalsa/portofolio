// Show uploaded project images automatically; keep the placeholder when no image exists yet.
document.querySelectorAll('.project-screenshot').forEach(img => {
 const showImage = () => {
  img.classList.add('is-loaded');

  const placeholder = img.parentElement.querySelector('.screenshot-placeholder');

  if (placeholder) placeholder.hidden = true;
 };

 img.addEventListener('load', showImage);

 img.addEventListener('error', () => {
  img.classList.remove('is-loaded');
 });

 if (img.complete && img.naturalWidth > 0) showImage();
});

